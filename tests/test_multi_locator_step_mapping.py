def test_governance_rejects_an_index_gap_in_stored_mappings():
    from automation.multi_locator.schema import MultiLocatorArtifact, StepLocatorCandidateSet, LocatorCandidate
    artifact = MultiLocatorArtifact(
        ml_automation_id="ML-X", source_automation_id="PW-X", testcase_id="TC-X",
        requirement_ids=["REQ-X"], test_data_set_id="TD-X",
        step_candidate_sets=[
            StepLocatorCandidateSet(1, "f", [LocatorCandidate(4, "STABLE_ATTRIBUTE", "#x", "src", "ref", "HIGH")]),
        ],
        testcase_step_mappings=[
            {"testcase_step_index": 0, "testcase_step_text": "a", "automation_step_orders": [1], "maps_to_assertions": False},
            {"testcase_step_index": 2, "testcase_step_text": "c", "automation_step_orders": [], "maps_to_assertions": True},  # gap at index 1
        ],
    )
    governed = govern_multi_locator_artifact(artifact)
    assert governed.governance_status == MultiLocatorGovernanceStatus.REJECTED
    assert any("TESTCASE_STEP_MAPPING_INDEX_GAP" in r for r in governed.reasons)


