@pytest.fixture(scope="module")
def real_testcase_payload():
    payload = load_latest(tp.BASE_DIR, "TC-REQ-ACO-03-01")
    if payload is None:
        pytest.skip("Real corpus testcase TC-REQ-ACO-03-01 not present on disk in this environment")
    return payload


def test_same_testcase_two_datasets_identical_business_steps_distinct_ids(real_testcase_payload):
    payload_d1 = resolve_source_automation_payload("PW-TC-REQ-ACO-03-01-01", "TD-TC-REQ-ACO-03-01-01")
    payload_d2 = resolve_source_automation_payload("PW-TC-REQ-ACO-03-01-01", "TD-TC-REQ-ACO-03-01-02")

    artifact_d1 = build_multi_locator_artifact(payload_d1, "ML-STEPTEST-D01", testcase_payload=real_testcase_payload)
    artifact_d2 = build_multi_locator_artifact(payload_d2, "ML-STEPTEST-D02", testcase_payload=real_testcase_payload)

    # Business-step structure (the mapping) is identical -- only the
    # backing test_data_set_id and ml_automation_id differ.
    assert artifact_d1.testcase_step_mappings == artifact_d2.testcase_step_mappings
    assert artifact_d1.test_data_set_id != artifact_d2.test_data_set_id
    assert artifact_d1.ml_automation_id != artifact_d2.ml_automation_id

    field_order_d1 = [s.get("input_mapping") for s in payload_d1["steps"] if s.get("input_mapping")]
    field_order_d2 = [s.get("input_mapping") for s in payload_d2["steps"] if s.get("input_mapping")]
    assert field_order_d1 == field_order_d2
