import testcases.persist as tp


def _steps(*action_types):
    return [{"step_order": i + 1, "action_type": a} for i, a in enumerate(action_types)]


# ---------------------------------------------------------------------------
# build_step_mapping — unit
# ---------------------------------------------------------------------------

def test_single_testcase_step_maps_every_automation_step():
    steps = _steps(ActionType.NAVIGATE, ActionType.FILL, ActionType.CLICK)
    mappings = build_step_mapping(["Do the whole thing."], steps, has_assertions=True)
    assert len(mappings) == 1
    assert mappings[0].automation_step_orders == [1, 2, 3]
    assert mappings[0].maps_to_assertions is True


def test_two_testcase_steps_real_world_pattern():
    steps = _steps(ActionType.NAVIGATE, ActionType.FILL, ActionType.FILL, ActionType.CLICK)
    mappings = build_step_mapping(
        ["Perform the action described by the approved requirement.", "Observe the resulting system behavior."],
        steps, has_assertions=True,
    )
    assert len(mappings) == 2
    assert mappings[0].automation_step_orders == [1, 2, 3, 4]
    assert mappings[0].maps_to_assertions is False
    assert mappings[1].automation_step_orders == []
    assert mappings[1].maps_to_assertions is True


def test_richer_multi_step_testcase_splits_action_steps_in_order():
    """Demonstrates the mapping generalizes beyond the 2-generic-step
    real corpus, in case a future, richer testcase (e.g. a real live-LLM
    generation) supplies more specific steps."""
    steps = _steps(*([ActionType.NAVIGATE] + [ActionType.FILL] * 5 + [ActionType.CLICK]))
    business_steps = [
        "Navigate to the Demo Web Shop.",
        "Add the eligible product to the cart.",
        "Proceed to checkout.",
        "Enter the required billing information.",
        "Submit the checkout.",
        "Verify the expected result.",
    ]
    mappings = build_step_mapping(business_steps, steps, has_assertions=True)
    assert len(mappings) == 6
    # 7 real action steps split across 5 non-final business steps, in order
    all_action_orders = [m.automation_step_orders for m in mappings[:-1]]
    flattened = [o for chunk in all_action_orders for o in chunk]
    assert flattened == sorted(flattened) == list(range(1, 8))
    assert mappings[-1].maps_to_assertions is True
    assert mappings[-1].automation_step_orders == []


def test_no_action_steps_still_covers_every_testcase_step_without_fabricating_orders():
    mappings = build_step_mapping(["Step A.", "Step B.", "Observe."], [], has_assertions=True)
    assert len(mappings) == 3
    for m in mappings:
        assert m.automation_step_orders == []


