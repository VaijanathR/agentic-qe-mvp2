def test_full_coverage_passes_when_every_step_has_content_or_assertions():
    mappings = [
        TestcaseStepMapping(0, "a", [1, 2]),
        TestcaseStepMapping(1, "b", [], maps_to_assertions=True),
    ]
    result = validate_full_coverage(mappings, ["a", "b"])
    assert result["passed"] is True


def test_full_coverage_fails_when_a_step_has_neither():
    mappings = [
        TestcaseStepMapping(0, "a", [1, 2]),
        TestcaseStepMapping(1, "b", [], maps_to_assertions=False),
    ]
    result = validate_full_coverage(mappings, ["a", "b"])
    assert result["passed"] is False
    assert result["detail"]["missing_testcase_steps"] == [1]


def test_no_orphan_automation_steps_detects_an_unmapped_real_step():
    steps = _steps(ActionType.NAVIGATE, ActionType.FILL)
    mappings = [TestcaseStepMapping(0, "a", [1])]  # step_order 2 (FILL) never mapped
    result = validate_no_orphan_automation_steps(mappings, steps)
    assert result["passed"] is False
    assert result["detail"]["orphan_step_orders"] == [2]


def test_order_preserved_detects_a_regression():
    mappings = [
        TestcaseStepMapping(0, "a", [3, 4]),
        TestcaseStepMapping(1, "b", [1, 2]),  # regresses behind step 0's max
    ]
    result = validate_order_preserved(mappings)
    assert result["passed"] is False


def test_order_preserved_passes_for_ascending_chunks():
    mappings = [
        TestcaseStepMapping(0, "a", [1, 2]),
        TestcaseStepMapping(1, "b", [3, 4]),
    ]
    assert validate_order_preserved(mappings)["passed"] is True


