"""
Tests for automation/multi_locator/step_mapping.py — testcase-step <->
automation-step traceability — and for the multi-dataset-independence
requirement (the same testcase's business steps must be identical
regardless of which persisted dataset variant is used).

See automation/multi_locator/step_mapping.py's own module docstring for
the disclosed, deterministic mapping heuristic and why today's entire
real testcase corpus (generated by the disclosed StubLLMClient) only
ever exercises the simple "N-1 concrete steps + 1 final observe step"
case in practice.
"""
